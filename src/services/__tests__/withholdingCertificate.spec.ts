import { describe, expect, it } from 'vitest'
import { normaliseText, parseWithholdingCertificate } from '../withholdingCertificate'

/** ข้อความแบบที่ดึงได้จาก PDF 50 ทวิ ของนายจ้าง (เรียงตามแถวของแบบฟอร์ม) */
const PDF_TEXT = `
หนังสือรับรองการหักภาษี ณ ที่จ่าย ตามมาตรา 50 ทวิ แห่งประมวลรัษฎากร
ผู้มีหน้าที่หักภาษี ณ ที่จ่าย บริษัท ตัวอย่าง จำกัด เลขประจำตัวผู้เสียภาษีอากร 0105551234567
ผู้ถูกหักภาษี ณ ที่จ่าย นายสมชาย ใจดี เลขประจำตัวประชาชน 1234567890123
ประเภทเงินได้พึงประเมินที่จ่าย วัน เดือน หรือปีภาษี ที่จ่าย จำนวนเงินที่จ่าย ภาษีที่หักและนำส่งไว้
1. เงินเดือน ค่าจ้าง เบี้ยเลี้ยง โบนัส ฯลฯ ตามมาตรา 40 (1) 2568 620,000.00 24,000.00
2. ค่าธรรมเนียม ค่านายหน้า ฯลฯ ตามมาตรา 40 (2)
3. ค่าแห่งลิขสิทธิ์ ฯลฯ ตามมาตรา 40 (3)
5. การจ่ายเงินได้ที่ต้องหักภาษี ณ ที่จ่าย ตามคำสั่งกรมสรรพากรที่ออกตามมาตรา 3 เตรส เช่น ค่าจ้างทำของ ค่าโฆษณา ค่าบริการ
รวมเงินที่จ่ายและภาษีที่หักนำส่ง 620,000.00 24,000.00
เงินที่จ่ายเข้า กบข./กสจ./กองทุนสงเคราะห์ครูโรงเรียนเอกชน บาท กองทุนประกันสังคม 9,000.00 บาท กองทุนสำรองเลี้ยงชีพ 31,000.00 บาท
`

describe('อ่าน 50 ทวิ จาก PDF', () => {
  const r = parseWithholdingCertificate(PDF_TEXT)

  it('อ่านแถวเงินเดือนได้ทั้งยอดจ่ายและภาษี โดยไม่หยิบปี พ.ศ.', () => {
    expect(r.rows).toEqual([
      expect.objectContaining({ kind: '40(1)', incomeKey: 'salary', paid: 620_000, tax: 24_000, review: false }),
    ])
  })

  it('แถว 3 เตรสที่มีคำว่าค่าจ้างทำของไม่ถูกนับเป็นเงินเดือน และแถวว่างไม่ถูกนับ', () => {
    expect(r.rows.filter((x) => x.kind === '40(1)')).toHaveLength(1)
    expect(r.rows.some((x) => x.kind === '3tres')).toBe(false)
  })

  it('แถวรวมตรงกับผลรวม', () => {
    expect(r.total).toEqual({ paid: 620_000, tax: 24_000 })
    expect(r.mismatch).toBe(false)
  })

  it('แยกยอดกองทุนที่อยู่บรรทัดเดียวกัน', () => {
    expect(r.funds).toEqual({ gpf: 0, socialSecurity: 9_000, providentFund: 31_000 })
  })

  it('เลขผู้จ่ายเงินคือเลข 13 หลักตัวแรก', () => {
    expect(r.payerTaxId).toBe('0105551234567')
  })
})

describe('อ่าน 50 ทวิ จาก OCR', () => {
  it('รับเลขไทย ตัวเลขขึ้นบรรทัดถัดไป และจุลภาคที่ OCR อ่านเป็นจุด', () => {
    const text = `
      ๕. การจ่ายเงินได้ตามมาตรา ๓ เตรส เช่น ค่าบริการ
      ๓๑ ธ.ค. ๖๘   120.000.00   3,600.00
      รวมเงินที่จ่ายและภาษีที่หักนำส่ง 120,000.00 3,600.00`
    const r = parseWithholdingCertificate(text)
    expect(r.rows).toEqual([
      expect.objectContaining({ kind: '3tres', incomeKey: 'freelance', paid: 120_000, tax: 3_600, review: true }),
    ])
  })

  it('อ่านแถวไม่ได้แต่มีแถวรวม ใช้แถวรวมและให้ตรวจ', () => {
    const r = parseWithholdingCertificate('รวมเงินที่จ่ายและภาษีที่หักนำส่ง 50,000.00 500.00')
    expect(r.rows).toEqual([expect.objectContaining({ paid: 50_000, tax: 500, review: true })])
  })

  it('ผลรวมไม่ตรงแถวรวมแจ้งว่าอาจอ่านพลาด', () => {
    const r = parseWithholdingCertificate(
      'เงินเดือน ตามมาตรา 40 (1) 100,000.00 1,000.00\nรวมเงินที่จ่ายและภาษีที่หักนำส่ง 150,000.00 2,500.00',
    )
    expect(r.mismatch).toBe(true)
  })

  it('จัดรูป 40 ( 1 ) ให้เป็น 40(1)', () => {
    expect(normaliseText('ตามมาตรา 40 ( 1 )')).toBe('ตามมาตรา 40(1)')
  })
})
