export const QUIZ_ROUND_SIZE = 5

/** สุ่มคำถามรอบใหม่ (ไม่ซ้ำกันในรอบเดียว) */
export function pickQuestions(random: () => number = Math.random): QuizQuestion[] {
  const pool = [...QUIZ_QUESTIONS]
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1))
    ;[pool[i], pool[j]] = [pool[j]!, pool[i]!]
  }
  return pool.slice(0, QUIZ_ROUND_SIZE)
}
